interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, fallback?: string) => string;
  errorMessage: (code: string) => string;
  locale: string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function detectLanguage(): Language {
  const stored = localStorage.getItem('teamcal_language');
  if (stored === 'fr' || stored === 'en' || stored === 'de') return stored;
  const browser = navigator.language.slice(0, 2);
  if (browser === 'fr' || browser === 'en' || browser === 'de') return browser;
  return 'fr';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(detectLanguage);
  const setLanguage = useCallback((value: Language) => {
    localStorage.setItem('teamcal_language', value);
    setLanguageState(value);
  }, []);
  const t = useCallback(
    (key: string, fallback?: string) => dictionaries[language][key] ?? dictionaries.en[key] ?? fallback ?? key,
    [language]
  );
  const errorMessage = useCallback(
    (code: string) => {
      const key = errorKeys[code];
      return key ? t(key) : code;
    },
    [t]
  );
  const locale = language === 'de' ? 'de-DE' : language === 'en' ? 'en-GB' : 'fr-FR';
  const value = useMemo(
    () => ({ language, setLanguage, t, errorMessage, locale }),
    [language, setLanguage, t, errorMessage, locale]
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used within I18nProvider');
  return context;
}

export function languageLabel(language: Language): string {
  return language === 'fr' ? 'Français' : language === 'en' ? 'English' : 'Deutsch';
}
